// The slug above the headline says how the run ended. `caught` means Trump made the arrest.
export function frontPage(cause, edition, { overtime = false, caught = false } = {}) {
    const stories = receipts[cause] || receipts.protestor;
    const [headline, copy] = stories[edition % stories.length];
    const slug = overtime ? 'Mamdani keeps NYC'
        : cause.startsWith('race:') ? 'Race desk'
        : caught ? 'Trump returns' : 'Stop press';
    return { slug, headline, copy };
}

